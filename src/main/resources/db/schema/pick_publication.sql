CREATE TABLE pick_publication_attempts (
    id UUID PRIMARY KEY,
    batch_id UUID NOT NULL,
    race_id UUID NOT NULL,
    season_id UUID NOT NULL,
    original_matchday_id UUID NOT NULL,
    original_home_team_id UUID NOT NULL,
    original_away_team_id UUID NOT NULL,
    content_version BIGINT NOT NULL,
    source_version BIGINT NOT NULL,
    origin VARCHAR(16) NOT NULL,
    output_type VARCHAR(24) NOT NULL,
    track_id UUID,
    car_id UUID,
    car_pool_entry_id UUID,
    track_name VARCHAR(255),
    car_name VARCHAR(1024),
    pool_entry_label VARCHAR(255),
    laps INTEGER,
    tyre_wear INTEGER,
    fuel_consumption INTEGER,
    refueling_speed INTEGER,
    initial_fuel VARCHAR(255),
    required_pit_stops INTEGER,
    time_progression_mode VARCHAR(24),
    time_progression_multiplier INTEGER,
    weather VARCHAR(255),
    time_of_day VARCHAR(255),
    available_tyres VARCHAR(255),
    mandatory_tyres VARCHAR(255),
    content_hash VARCHAR(64) NOT NULL,
    field_mask INTEGER NOT NULL,
    actor_id VARCHAR(128) NOT NULL,
    channel_id VARCHAR(64) NOT NULL,
    webhook_id VARCHAR(64) NOT NULL,
    target_message_id VARCHAR(64),
    template_hash VARCHAR(64) NOT NULL,
    request_manifest TEXT NOT NULL,
    request_hash VARCHAR(64) NOT NULL,
    runtime_generation VARCHAR(64) NOT NULL,
    captured_at TIMESTAMP(6) NOT NULL,
    state VARCHAR(16) NOT NULL,
    active_race_id UUID,
    message_id VARCHAR(64),
    completed_at TIMESTAMP(6),
    failure_code VARCHAR(64),
    reconciled_by VARCHAR(128),
    reconciliation_reason VARCHAR(1000),
    resolved_at TIMESTAMP(6),
    created_at TIMESTAMP(6),
    updated_at TIMESTAMP(6),
    CONSTRAINT uq_publication_active UNIQUE (active_race_id),
    CONSTRAINT ck_publication_version CHECK (content_version > 0),
    CONSTRAINT ck_publication_source CHECK ((origin = 'LEGACY' AND source_version = 0) OR (CASE origin WHEN 'APPROVAL' THEN 1 WHEN 'CORRECTION' THEN 1 ELSE 0 END = 1 AND source_version > 0)),
    CONSTRAINT ck_publication_output CHECK (CASE output_type WHEN 'SETTINGS' THEN 1 WHEN 'LOBBY_SETTINGS' THEN 1 WHEN 'MATCH_PREVIEW' THEN 1 ELSE 0 END = 1),
    CONSTRAINT ck_publication_fields CHECK (field_mask >= 0 AND field_mask <= 8191),
    CONSTRAINT ck_publication_lobby CHECK (output_type <> 'LOBBY_SETTINGS' OR MOD(FLOOR(field_mask / 2), 2) = 0),
    CONSTRAINT ck_publication_state CHECK (CASE state WHEN 'PREPARED' THEN 1 WHEN 'SUCCEEDED' THEN 1 WHEN 'FAILED' THEN 1 WHEN 'UNCERTAIN' THEN 1 WHEN 'ABANDONED' THEN 1 ELSE 0 END = 1),
    CONSTRAINT ck_publication_active CHECK ((CASE state WHEN 'PREPARED' THEN 1 WHEN 'UNCERTAIN' THEN 1 ELSE 0 END = 1 AND active_race_id IS NOT NULL AND active_race_id = race_id) OR (CASE state WHEN 'SUCCEEDED' THEN 1 WHEN 'FAILED' THEN 1 WHEN 'ABANDONED' THEN 1 ELSE 0 END = 1 AND active_race_id IS NULL)),
    CONSTRAINT ck_publication_completed CHECK ((state = 'PREPARED' AND completed_at IS NULL) OR (state <> 'PREPARED' AND completed_at IS NOT NULL)),
    CONSTRAINT ck_publication_message CHECK (state <> 'SUCCEEDED' OR (message_id IS NOT NULL AND CHAR_LENGTH(TRIM(message_id)) > 0)),
    CONSTRAINT ck_publication_chronology CHECK (completed_at IS NULL OR completed_at >= captured_at),
    CONSTRAINT ck_publication_resolution CHECK (resolved_at IS NULL OR (completed_at IS NOT NULL AND resolved_at >= completed_at)),
    CONSTRAINT fk_publication_race FOREIGN KEY (race_id) REFERENCES races(id) ON DELETE CASCADE,
    CONSTRAINT fk_publication_original_season FOREIGN KEY (season_id) REFERENCES seasons(id),
    CONSTRAINT fk_publication_original_day FOREIGN KEY (original_matchday_id) REFERENCES matchdays(id),
    CONSTRAINT fk_publication_original_home FOREIGN KEY (original_home_team_id) REFERENCES teams(id),
    CONSTRAINT fk_publication_original_away FOREIGN KEY (original_away_team_id) REFERENCES teams(id)
);
CREATE INDEX ix_publication_race_version ON pick_publication_attempts (race_id, content_version);
CREATE INDEX ix_publication_batch ON pick_publication_attempts (batch_id);

CREATE TABLE pick_publication_snapshots (
    id UUID PRIMARY KEY,
    attempt_id UUID NOT NULL,
    confirmed_at TIMESTAMP(6) NOT NULL,
    created_at TIMESTAMP(6),
    updated_at TIMESTAMP(6),
    CONSTRAINT uq_publication_snapshot UNIQUE (attempt_id),
    CONSTRAINT fk_publication_snapshot_attempt FOREIGN KEY (attempt_id) REFERENCES pick_publication_attempts(id) ON DELETE CASCADE
);
